package com.christian34.survivalgames.arena;

import org.bukkit.configuration.file.YamlConfiguration;
import org.jetbrains.annotations.Nullable;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/**
 * Makes a map smaller (/sg map trim): every game copies its map, a big one takes seconds. Removed are the chunks that
 * contain nothing but air (void maps), the unfinished chunks the server has only begun to generate (they are never
 * sent to the players) and the chunks far outside the world border of all arenas that use the map.
 * <p>
 * A chunk that isn't in the map is generated by the server when it is loaded. So a map without its empty chunks is
 * marked ({@link #MARKER}): its copies get a generator that keeps such chunks empty, instead of generating terrain
 * next to the map. Without unfinished chunks nothing changes: the server finishes them anyway.
 * <p>
 * Runs off the server thread (no Bukkit API).
 *
 * @author Christian34
 */
public final class MapTrimmer {
    /**
     * in the folder of a map: written by trimming
     */
    public static final String MARKER = "sg-map.yml";
    private static final Pattern REGION = Pattern.compile("r\\.(-?\\d+)\\.(-?\\d+)\\.mca");
    private static final Set<String> AIR = Set.of("minecraft:air", "minecraft:cave_air", "minecraft:void_air");
    private static final Set<String> FULL = Set.of("full", "minecraft:full");

    /**
     * what is done with a chunk
     */
    enum Kind {
        KEEP,
        /**
         * a generated chunk with nothing but air
         */
        EMPTY,
        /**
         * a chunk the server has only begun to generate (without entities)
         */
        UNFINISHED
    }
    /**
     * the folders of a world with region files, by chunk (region first: it decides what an empty chunk is)
     */
    private static final List<String> FOLDERS = List.of("region", "entities", "poi");

    /**
     * the chunks (inclusive) the players of an arena can see: inside the border and the view distance around it
     */
    public record Area(int minX, int minZ, int maxX, int maxZ) {
        /**
         * @param size   the size of the world border (blocks)
         * @param margin chunks around it
         */
        public static Area around(double centerX, double centerZ, int size, int margin) {
            double half = size / 2.0;
            return new Area((int) Math.floor((centerX - half) / 16) - margin,
                    (int) Math.floor((centerZ - half) / 16) - margin,
                    (int) Math.floor((centerX + half) / 16) + margin,
                    (int) Math.floor((centerZ + half) / 16) + margin);
        }

        boolean contains(int x, int z) {
            return x >= minX && x <= maxX && z >= minZ && z <= maxZ;
        }
    }

    /**
     * @param chunks  the chunks of the map
     * @param empty   removed chunks with nothing but air and unfinished chunks
     * @param outside removed chunks outside the areas
     * @param size    the size of the map before (bytes)
     * @param removed the bytes that are (or would be) removed
     */
    public record Result(int chunks, int empty, int outside, long size, long removed) {
        public int total() {
            return empty + outside;
        }
    }

    private MapTrimmer() {
    }

    /**
     * @return the size of all files in the folder (bytes)
     */
    public static long size(File folder) {
        if (!folder.isDirectory()) return folder.length();
        try (Stream<Path> walk = Files.walk(folder.toPath())) {
            return walk.filter(Files::isRegularFile).mapToLong(path -> path.toFile().length()).sum();
        } catch (IOException | RuntimeException ex) {
            return 0;
        }
    }

    /**
     * @return true if the chunks that aren't in the map stay empty (it has been trimmed)
     */
    public static boolean isVoid(@Nullable File map) {
        if (map == null) return false;
        File marker = new File(map, MARKER);
        return marker.isFile() && YamlConfiguration.loadConfiguration(marker).getBoolean("void");
    }

    /**
     * finds out what trimming would remove, without changing the map
     *
     * @param areas the parts the arenas use, null: the whole map is used (only empty chunks are removed)
     */
    public static Result analyse(File map, @Nullable List<Area> areas) throws IOException {
        return run(map, areas, null);
    }

    /**
     * trims the map: the files that change are saved in the backup first
     *
     * @param areas  the parts the arenas use, null: the whole map is used (only empty chunks are removed)
     * @param backup the zip file the old region files are saved in
     */
    public static Result trim(File map, @Nullable List<Area> areas, File backup) throws IOException {
        return run(map, areas, backup);
    }

    private static Result run(File map, @Nullable List<Area> areas, @Nullable File backup) throws IOException {
        File data = GameWorld.getMapData(map);
        long size = size(map);
        int chunks = 0;
        int empty = 0;
        int outside = 0;
        boolean air = false;
        long removed = 0;
        Backup zip = backup == null ? null : new Backup(backup);
        try {
            for (String region : regionNames(data)) {
                Matcher matcher = REGION.matcher(region);
                if (!matcher.matches()) continue;
                int regionX = Integer.parseInt(matcher.group(1));
                int regionZ = Integer.parseInt(matcher.group(2));
                // one region at a time: a big map doesn't fit into the memory
                Map<String, Map<Integer, RegionFile.Chunk>> files = new HashMap<>();
                for (String folder : FOLDERS) {
                    File file = new File(data, folder + "/" + region);
                    files.put(folder, file.isFile() ? RegionFile.read(file) : new HashMap<>());
                }
                Map<Integer, RegionFile.Chunk> blocks = files.get("region");
                Set<Integer> indices = new HashSet<>();
                files.values().forEach(file -> indices.addAll(file.keySet()));
                Set<Integer> remove = new HashSet<>();
                for (int index : indices) {
                    int x = regionX * 32 + (index & 31);
                    int z = regionZ * 32 + (index >> 5);
                    boolean inRegion = blocks.containsKey(index);
                    if (inRegion) chunks++;
                    if (areas != null && areas.stream().noneMatch(area -> area.contains(x, z))) {
                        remove.add(index);
                        if (inRegion) outside++;
                    } else if (inRegion) {
                        Kind kind = classify(blocks.get(index), files.get("entities").get(index));
                        if (kind == Kind.KEEP) continue;
                        remove.add(index);
                        empty++;
                        air |= kind == Kind.EMPTY;
                    }
                }
                if (remove.isEmpty()) continue;
                for (String folder : FOLDERS) {
                    Map<Integer, RegionFile.Chunk> file = files.get(folder);
                    if (file.isEmpty()) continue;
                    int before = file.size();
                    for (int index : remove) {
                        RegionFile.Chunk chunk = file.remove(index);
                        if (chunk != null) removed += chunk.size();
                    }
                    if (file.isEmpty()) removed += 2L * RegionFile.SECTOR;
                    if (zip == null || file.size() == before) continue;
                    File target = new File(data, folder + "/" + region);
                    zip.add(folder + "/" + region, target);
                    RegionFile.write(target, file);
                }
                for (int index : remove) {
                    // a chunk too big for the region file
                    String name = "c." + (regionX * 32 + (index & 31)) + "." + (regionZ * 32 + (index >> 5)) + ".mcc";
                    File external = new File(data, "region/" + name);
                    if (!external.isFile()) continue;
                    removed += external.length();
                    if (zip == null) continue;
                    zip.add("region/" + name, external);
                    Files.delete(external.toPath());
                }
            }
        } finally {
            if (zip != null) zip.close();
        }
        if (zip != null && air) writeMarker(map);
        return new Result(chunks, empty, outside, size, removed);
    }

    /**
     * the zip file the old region files are saved in before they change (created with the first one)
     */
    private static final class Backup {
        private final File target;
        private final File temp;
        @Nullable
        private ZipOutputStream zip;

        private Backup(File target) {
            this.target = target;
            this.temp = new File(target.getParentFile(), target.getName() + ".tmp");
        }

        void add(String name, File file) throws IOException {
            if (zip == null) {
                File parent = target.getParentFile();
                if (parent != null && !parent.isDirectory() && !parent.mkdirs()) {
                    throw new IOException("Couldn't create " + parent);
                }
                zip = new ZipOutputStream(Files.newOutputStream(temp.toPath()));
            }
            zip.putNextEntry(new ZipEntry(name));
            Files.copy(file.toPath(), zip);
            zip.closeEntry();
        }

        /**
         * finishes the zip file - also after an error: it holds the files changed so far
         */
        void close() throws IOException {
            if (zip == null) return;
            zip.close();
            Files.move(temp.toPath(), target.toPath(), StandardCopyOption.REPLACE_EXISTING);
        }
    }

    private static Set<String> regionNames(File data) {
        Set<String> names = new HashSet<>();
        for (String folder : FOLDERS) {
            String[] files = new File(data, folder).list();
            if (files != null) names.addAll(List.of(files));
        }
        return names;
    }

    /**
     * @return true if the chunk has nothing but air, no block entities and no entities
     */
    static boolean isEmpty(RegionFile.Chunk chunk, @Nullable RegionFile.Chunk entities) {
        return classify(chunk, entities) == Kind.EMPTY;
    }

    /**
     * @return what is done with the chunk - a chunk it can't read is kept
     */
    static Kind classify(RegionFile.Chunk chunk, @Nullable RegionFile.Chunk entities) {
        try {
            Map<String, Object> nbt = RegionFile.readNbt(chunk);
            if (nbt == null || !(nbt.get("sections") instanceof List<?> sections)) return Kind.KEEP;
            if (entities != null) {
                Map<String, Object> entityNbt = RegionFile.readNbt(entities);
                if (entityNbt == null || !(entityNbt.get("Entities") instanceof List<?> list) || !list.isEmpty()) {
                    return Kind.KEEP;
                }
            }
            if (nbt.get("Entities") instanceof List<?> old && !old.isEmpty()) return Kind.KEEP;
            Object status = nbt.get("Status");
            if (status != null && !FULL.contains(String.valueOf(status))) return Kind.UNFINISHED;
            if (nbt.get("block_entities") instanceof List<?> blockEntities && !blockEntities.isEmpty()) return Kind.KEEP;
            boolean blocks = false;
            for (Object section : sections) {
                if (!(section instanceof Map<?, ?> map) || !(map.get("block_states") instanceof Map<?, ?> states)) continue;
                if (!(states.get("palette") instanceof List<?> palette)) return Kind.KEEP;
                for (Object block : palette) {
                    if (!(block instanceof Map<?, ?> state) || !AIR.contains(String.valueOf(state.get("Name")))) {
                        return Kind.KEEP;
                    }
                }
                blocks = true;
            }
            // a chunk without any block data is stored in a way this doesn't know
            return blocks ? Kind.EMPTY : Kind.KEEP;
        } catch (IOException | RuntimeException ex) {
            return Kind.KEEP;
        }
    }

    private static void writeMarker(File map) throws IOException {
        YamlConfiguration marker = new YamlConfiguration();
        marker.options().setHeader(List.of("Written by /sg map trim: its empty chunks have been removed, so the chunks "
                + "that aren't in the map stay empty in the games (no terrain is generated next to the map)."));
        marker.set("void", true);
        marker.save(new File(map, MARKER));
    }

}
